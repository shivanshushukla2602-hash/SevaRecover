/**
 * Universal translation trigger: Sets the googtrans cookie and triggers
 * the Google Translate combo element so that every single text node in
 * the entire DOM is dynamically translated in real-time.
 */
export const triggerGoogleTranslate = (lang: string) => {
  if (typeof document === 'undefined') return;

  const googleCode = lang === 'zh' ? 'zh-CN' : lang === 'or' ? 'or' : lang;

  // Set / clear the googtrans cookie
  const domain = window.location.hostname;
  if (lang === 'en') {
    document.cookie = 'googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/;';
    document.cookie = 'googtrans=/en/en; path=/;';
    if (domain && domain !== 'localhost' && !domain.startsWith('127.')) {
      document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; domain=.${domain}; path=/;`;
      document.cookie = `googtrans=/en/en; domain=.${domain}; path=/;`;
    }
  } else {
    const cookieVal = `/en/${googleCode}`;
    document.cookie = `googtrans=${cookieVal}; path=/;`;
    if (domain && domain !== 'localhost' && !domain.startsWith('127.')) {
      document.cookie = `googtrans=${cookieVal}; domain=.${domain}; path=/;`;
    }
  }

  // Find the Google Translate select dropdown and trigger the change event
  const tryTrigger = (): boolean => {
    const selectElem = document.querySelector('.goog-te-combo') as HTMLSelectElement | null;
    if (selectElem) {
      const targetValue = lang === 'en' ? 'en' : googleCode;
      if (selectElem.value !== targetValue) {
        selectElem.value = targetValue;
        selectElem.dispatchEvent(new Event('change'));
      }
      return true;
    }
    return false;
  };

  if (!tryTrigger()) {
    let attempts = 0;
    const interval = setInterval(() => {
      attempts++;
      if (tryTrigger() || attempts >= 12) {
        clearInterval(interval);
      }
    }, 250);
  }
};

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem('sevarecover-lang') as Language;
    return saved || 'en';
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem('sevarecover-lang', lang);
    triggerGoogleTranslate(lang);
  };

  // On mount and language changes, ensure full-page translation engine is triggered
  React.useEffect(() => {
    if (language !== 'en') {
      triggerGoogleTranslate(language);
    }
  }, [language]);

  const t = (key: string): string => {
    return UI_TRANSLATIONS[language]?.[key] || UI_TRANSLATIONS['en']?.[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};

